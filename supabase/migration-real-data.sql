--   1) เพิ่มคอลัมน์ใหม่ในตาราง programs (รหัสหลักสูตร TCAS, โครงการ, ลิงก์, คะแนนปีก่อน)
--   2) สร้างตาราง program_score_history เก็บคะแนนต่ำสุด-สูงสุดย้อนหลังหลายปี
