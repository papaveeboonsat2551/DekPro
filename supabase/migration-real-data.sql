alter table public.programs
  add column if not exists tcas_program_id text,        -- รหัสหลักสูตร 15 หลักของ TCAS
  add column if not exists project_id text,             -- รหัสโครงการ (รอบ 2)
  add column if not exists project_name text,           -- ชื่อโครงการ (รอบ 2)
  add column if not exists quota int,                   -- จำนวนที่รับ
  add column if not exists link text,                   -- ลิงก์ประกาศของมหาวิทยาลัย
  add column if not exists prev_year int,               -- ปีล่าสุดที่มีคะแนน เช่น 2569
  add column if not exists prev_min_score numeric,      -- คะแนนรวมต่ำสุดของผู้ที่ได้รับคัดเลือกปีนั้น
  add column if not exists prev_max_score numeric;      -- คะแนนรวมสูงสุด

create index if not exists programs_pick_idx on public.programs (round, university, faculty);

create table if not exists public.program_score_history (
  id              bigint generated by default as identity primary key,
  program_id      bigint not null references public.programs(id) on delete cascade,
  year            int    not null,                       -- ปี พ.ศ. ของการสอบ เช่น 2569
  round           int    not null default 3,
  quota           int,                                   -- จำนวนที่รับ
  applicants      int,                                   -- ผู้สมัคร
  passed          int,                                   -- ผู้ผ่านการคัดเลือก
  min_score_first numeric,                               -- ต่ำสุด ประมวลผลครั้งที่ 1
  max_score_first numeric,
  min_score_final numeric,                               -- ต่ำสุด หลังประมวลผลครั้งที่ 2 (ค่าที่แอปใช้)
  max_score_final numeric
);
create index if not exists score_history_program_idx on public.program_score_history (program_id, year desc);

alter table public.program_score_history enable row level security;
drop policy if exists "ทุกคนอ่านประวัติคะแนนได้" on public.program_score_history;
create policy "ทุกคนอ่านประวัติคะแนนได้" on public.program_score_history for select using (true);
grant select on public.program_score_history to anon, authenticated;
