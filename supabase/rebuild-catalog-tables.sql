-- ใช้เมื่อ: Table Editor มีตารางแปลก ๆ เช่น "program", "program_subjectsfinal" หรือตาราง
--   topics / program_score_history ไม่มีคอลัมน์ id (เกิดจากกด "สร้างตารางใหม่จากไฟล์ CSV")
-- ทำอะไร: ลบเฉพาะตารางข้อมูลมหาวิทยาลัยที่ "ว่าง" แล้วสร้างใหม่ตามโครงสร้างที่แอปต้องการ
-- ไม่แตะ: profiles, checklist_items, exam_dates, reading_sessions, exam_sessions, auth.users และตาราง programs
-- =====================================================================

-- 1) ลบตารางที่สร้างผิด (ว่างทั้งหมด)
drop table if exists public.program;
drop table if exists public.program_subjectsfinal;
drop table if exists public.program_subjects;
drop table if exists public.program_score_history;
drop table if exists public.topics;

-- 2) programs: เพิ่มคอลัมน์ใหม่ (ถ้ามีอยู่แล้วจะข้าม)
alter table public.programs
  add column if not exists tcas_program_id text,
  add column if not exists project_id text,
  add column if not exists project_name text,
  add column if not exists quota int,
  add column if not exists link text,
  add column if not exists prev_year int,
  add column if not exists prev_min_score numeric,
  add column if not exists prev_max_score numeric;
create index if not exists programs_pick_idx on public.programs (round, university, faculty);

-- 3) สร้างตารางที่ลบไปใหม่ตามโครงสร้างที่ถูกต้อง
create table public.program_subjects (
  id              bigint generated by default as identity primary key,
  program_id      bigint not null references public.programs(id) on delete cascade,
  subject         text not null,
  content_subject text,
  weight_percent  numeric not null default 0,
  min_score       numeric,
  last_min        numeric,
  last_avg        numeric,
  last_max        numeric
);
create index program_subjects_program_idx on public.program_subjects (program_id);

create table public.topics (
  id         bigint generated by default as identity primary key,
  subject    text not null,
  topic      text not null,
  sort_order int  not null default 0
);

create table public.program_score_history (
  id              bigint generated by default as identity primary key,
  program_id      bigint not null references public.programs(id) on delete cascade,
  year            int    not null,
  round           int    not null default 3,
  quota           int,
  applicants      int,
  passed          int,
  min_score_first numeric,
  max_score_first numeric,
  min_score_final numeric,
  max_score_final numeric
);
create index score_history_program_idx on public.program_score_history (program_id, year desc);

-- 4) ความปลอดภัย: ทุกคนอ่านได้ ไม่มีใครเขียนผ่านเว็บได้ (เขียนได้เฉพาะตอนคุณ import จาก Dashboard)
alter table public.programs              enable row level security;
alter table public.program_subjects      enable row level security;
alter table public.topics                enable row level security;
alter table public.program_score_history enable row level security;

drop policy if exists "ทุกคนอ่านข้อมูลมหาลัยได้"   on public.programs;
drop policy if exists "ทุกคนอ่านวิชาที่ต้องสอบได้" on public.program_subjects;
drop policy if exists "ทุกคนอ่านหัวข้อเนื้อหาได้"  on public.topics;
drop policy if exists "ทุกคนอ่านประวัติคะแนนได้"   on public.program_score_history;
create policy "ทุกคนอ่านข้อมูลมหาลัยได้"   on public.programs              for select using (true);
create policy "ทุกคนอ่านวิชาที่ต้องสอบได้" on public.program_subjects      for select using (true);
create policy "ทุกคนอ่านหัวข้อเนื้อหาได้"  on public.topics                for select using (true);
create policy "ทุกคนอ่านประวัติคะแนนได้"   on public.program_score_history for select using (true);

grant select on public.programs, public.program_subjects, public.topics, public.program_score_history to anon, authenticated;

-- 5) ตรวจ: ต้องได้ 0 ทั้ง 4 ช่อง และไม่มี error
select (select count(*) from public.programs)              as programs,
       (select count(*) from public.program_subjects)      as subjects,
       (select count(*) from public.topics)                as topics,
       (select count(*) from public.program_score_history) as history;

-- ให้ API เห็นตารางใหม่ทันที
notify pgrst, 'reload schema';
