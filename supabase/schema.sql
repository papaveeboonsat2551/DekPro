-- ---------------------------------------------------------------------
-- 1) Uni & Requirement : ข้อมูลมหาลัย คณะ สาขา และเกณฑ์ (ทุกคนอ่านได้)
-- ---------------------------------------------------------------------
create table public.programs (
  id          bigint primary key,
  university  text not null,
  faculty     text not null,
  major       text not null,
  round       int  not null check (round in (2, 3)),   -- 2 = Quota, 3 = Admission
  min_gpax    numeric(3,2) not null default 0,        -- เกรดเฉลี่ย 5 เทอมขั้นต่ำ
  data_year   int,                                    -- ปีของข้อมูลเกณฑ์/คะแนน
  is_estimate boolean not null default true,          -- true = เกณฑ์ปีนี้ยังไม่ออก ใช้ข้อมูลเก่าคาดการณ์
  note        text
);

create table public.program_subjects (
  id              bigint generated by default as identity primary key,
  program_id      bigint not null references public.programs(id) on delete cascade,
  subject         text not null,     -- วิชาที่ต้องสอบ เช่น TPAT3, A-Level ฟิสิกส์
  content_subject text,              -- วิชาเนื้อหาที่ต้องเก็บ เช่น ฟิสิกส์ (ใช้สร้างเช็คลิสต์)
  weight_percent  numeric not null default 0,
  min_score       numeric,           -- คะแนนขั้นต่ำตามเกณฑ์ (ไม่มี = null หรือ 0)
  last_min        numeric,           -- คะแนนต่ำสุดของคนที่ติดปีก่อน
  last_avg        numeric,           -- คะแนนเฉลี่ยของคนที่ติดปีก่อน
  last_max        numeric            -- คะแนนสูงสุดของคนที่ติดปีก่อน
);

create table public.topics (
  id         bigint generated by default as identity primary key,
  subject    text not null,          -- ต้องตรงกับ program_subjects.content_subject
  topic      text not null,
  sort_order int  not null default 0
);


-- ---------------------------------------------------------------------
-- 2) User : โปรไฟล์ผู้ใช้ (อีเมล/รหัสผ่านเก็บใน auth.users ของ Supabase
--    ซึ่งเข้ารหัสรหัสผ่านให้อัตโนมัติ และบังคับ 1 อีเมล = 1 บัญชี)
-- ---------------------------------------------------------------------
create table public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  email        text not null unique,
  first_name   text,
  last_name    text,
  school       text,
  age          int check (age between 10 and 30),
  grade_level  text,                                  -- '1/1' ... '6/2' (ม.ปี/เทอม)
  target_round int check (target_round in (2, 3)),
  program_id   bigint references public.programs(id) on delete set null,
  -- เกรดแต่ละเทอม: 0.00 = เกรดยังไม่ออก, ที่เหลือต้องอยู่ระหว่าง 1.00–4.00
  gpa_4_1 numeric(3,2) not null default 0 check (gpa_4_1 = 0 or gpa_4_1 between 1 and 4),
  gpa_4_2 numeric(3,2) not null default 0 check (gpa_4_2 = 0 or gpa_4_2 between 1 and 4),
  gpa_5_1 numeric(3,2) not null default 0 check (gpa_5_1 = 0 or gpa_5_1 between 1 and 4),
  gpa_5_2 numeric(3,2) not null default 0 check (gpa_5_2 = 0 or gpa_5_2 between 1 and 4),
  gpa_6_1 numeric(3,2) not null default 0 check (gpa_6_1 = 0 or gpa_6_1 between 1 and 4),
  gpa_6_2 numeric(3,2) not null default 0 check (gpa_6_2 = 0 or gpa_6_2 between 1 and 4),
  updated_at   timestamptz not null default now()
);

-- สมัครสมาชิกเมื่อไหร่ สร้างแถวโปรไฟล์ว่างให้อัตโนมัติ
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ---------------------------------------------------------------------
-- 3) Checklist : หัวข้อที่ต้องเก็บ + วิชาที่ต้องสอบ ของผู้ใช้แต่ละคน
-- ---------------------------------------------------------------------
create table public.checklist_items (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  program_id bigint references public.programs(id) on delete cascade,
  kind       text not null check (kind in ('content', 'exam')),
  subject    text not null,
  title      text not null,
  sort_order int  not null default 0,   -- ใช้คืนตำแหน่งเดิมเมื่อเอาติ๊กออก (แบบ Google Keep)
  done       boolean not null default false,
  done_at    timestamptz
);


-- ---------------------------------------------------------------------
-- 4) Study Plan : วันเริ่มอ่าน + วันสอบ (วิชาละ 1 แถว)
-- ---------------------------------------------------------------------
create table public.exam_dates (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  subject    text not null,
  start_date date not null default current_date,
  exam_at    timestamptz not null,
  unique (user_id, subject)
);


-- ---------------------------------------------------------------------
-- 5) Study Assist : เวลาอ่านหนังสือ + ผลการจับเวลาทำข้อสอบ
-- ---------------------------------------------------------------------
create table public.reading_sessions (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  subject    text not null,
  started_at timestamptz not null,
  seconds    int not null check (seconds >= 0)
);

create table public.exam_sessions (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  subject    text not null,
  topic      text not null,
  attempt_no int  not null,              -- สอบหัวข้อนี้เป็นครั้งที่เท่าไหร่
  seconds    int  not null check (seconds >= 0),
  done_q     int  not null,              -- ทำไปกี่ข้อ
  total_q    int  not null,              -- จากทั้งหมดกี่ข้อ
  correct    int  not null,
  wrong      int  not null,
  created_at timestamptz not null default now(),
  check (done_q between 0 and total_q),
  check (correct >= 0 and wrong >= 0 and correct + wrong <= done_q)
);


-- ---------------------------------------------------------------------
-- 6) Row Level Security : ผู้ใช้เห็น/แก้ได้เฉพาะข้อมูลของตัวเอง
--    (ทำให้ใส่ key ของ Supabase ในหน้าเว็บสาธารณะได้อย่างปลอดภัย)
-- ---------------------------------------------------------------------
alter table public.programs         enable row level security;
alter table public.program_subjects enable row level security;
alter table public.topics           enable row level security;
alter table public.profiles         enable row level security;
alter table public.checklist_items  enable row level security;
alter table public.exam_dates       enable row level security;
alter table public.reading_sessions enable row level security;
alter table public.exam_sessions    enable row level security;

create policy "ทุกคนอ่านข้อมูลมหาลัยได้"   on public.programs         for select using (true);
create policy "ทุกคนอ่านวิชาที่ต้องสอบได้" on public.program_subjects for select using (true);
create policy "ทุกคนอ่านหัวข้อเนื้อหาได้"  on public.topics           for select using (true);

create policy "เจ้าของเท่านั้น" on public.profiles
  for all using (id = auth.uid()) with check (id = auth.uid());
create policy "เจ้าของเท่านั้น" on public.checklist_items
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "เจ้าของเท่านั้น" on public.exam_dates
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "เจ้าของเท่านั้น" on public.reading_sessions
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "เจ้าของเท่านั้น" on public.exam_sessions
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

grant select on public.programs, public.program_subjects, public.topics to anon, authenticated;
grant select, insert, update, delete on
  public.profiles, public.checklist_items, public.exam_dates,
  public.reading_sessions, public.exam_sessions
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;
